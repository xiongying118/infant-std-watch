def main() -> int:
    keys = [m["moduleKey"] for m in M]
    assert len(keys) == len(set(keys)), "moduleKey 有重复：%s" % [
        k for k in keys if keys.count(k) > 1]
    need = {"nutrient_calc", "formula_version", "material_sub",
            "human_milk_research", "pilot_scaleup", "shelf_life",
            "reg_filing", "change_control"}
    missing = need - set(keys)
    assert not missing, "缺必备模块：%s" % missing

    gnames = [g for g, _, _ in GROUPS]
    for m in M:
        assert m["group"] in gnames, "%s 的 group 不在分组里" % m["moduleKey"]
        for f in ("name", "summary", "whenToUse", "template", "case"):
            assert m.get(f), "%s 缺字段 %s" % (m["moduleKey"], f)
        assert 3 <= len(m["steps"]) <= 6, \
            "%s steps 应为 3~6 步，实际 %d" % (m["moduleKey"], len(m["steps"]))
        assert all(isinstance(s, str) and len(s) >= 8 for s in m["steps"]), \
            "%s 步骤要动宾短语" % m["moduleKey"]
        assert "|" in m["template"], "%s template 要用竖线分隔字段" % m["moduleKey"]

    # 法规口径检查：核心模块必须出现对应标准号
    # ★ 检查前先归一化 ★
    #   页面里写成紧凑形式「GB 10765/10766/10767」，
    #   按字面找 "GB 10766" 会找不到（斜杠后面没有 "GB " 前缀）。
    #   → 把斜杠换成顿号再查。
    LAW = {
        "reg_law": ["GB 10765", "GB 10766", "GB 10767", "GB 19644"],
        "nutrient_calc": ["GB 10765", "GB 10766", "GB 10767"],
        "raw_material_basis": ["GB 10765", "GB 10766", "GB 10767"],
    }
    byKey = {m["moduleKey"]: m for m in M}
    for k, laws in LAW.items():
        txt = json.dumps(byKey[k], ensure_ascii=False)
        flat = txt.replace("/", "、").replace("，", "、")
        for law in laws:
            assert law in flat, "%s 缺法规口径 %s" % (k, law)

    # ★ 合并可交互组件定义 ★
    miss = []
    for m_ in M:
        w = RW.get(m_["moduleKey"])
        if not w:
            miss.append(m_["moduleKey"]); continue
        m_["widget"] = w
    assert not miss, "这些模块还没有 widget：%s" % miss
    print("  18 个模块全部挂上可交互组件")

    out = {"groups": [g for g, _, _ in GROUPS], "catMeta": CAT_META, "modules": M}
    js = json.dumps([out], ensure_ascii=False, indent=1)

    p = os.path.join(DATA, "_rdtools.txt")
    io.open(p, "w", encoding="utf-8").write(js)
    print("已写入 %s（%d 字节）" % (p, os.path.getsize(p)))
    print("  %d 个功能点· %d 个分组" % (len(M), len(GROUPS)))
    for g in gnames:
        items = [x for x in M if x["group"] == g]
        print("    %s %-8s %d 个 · %d 步"
              % (CAT_META[g]["icon"], g, len(items),
                 sum(len(x["steps"]) for x in items)))
    return 0


