def main() -> int:
    bad = 0

    print("=== 检测方法细分 ===")
    for title, want in CASES:
        got = D.detect_sub("", title)
        ok = got == want
        if not ok:
            bad += 1
        print("  {} {} → {}{}".format(
            "✓" if ok else "✗ 错", title[10:44], got,
            "" if ok else "  (期望 " + want + ")"))

    print()
    print("=== 产品标准细分 ===")
    for title, want in PRODUCT_CASES:
        got = D.product_sub("", title)
        ok = got == want
        if not ok:
            bad += 1
        print("  {} {} → {}{}".format(
            "✓" if ok else "✗ 错", title[10:40], got,
            "" if ok else "  (期望 " + want + ")"))

    print()
    print("=== 兜底检查：真实库中不应有大量「其它检测方法」 ===")
    import json
    import io
    p = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                     "..", "data", "general_refs.json")
    if os.path.exists(p):
        g = json.load(io.open(p, encoding="utf-8"))
        others = [k for k, v in (g.get("details") or {}).items()
                  if v.get("category") == "test"
                  and D.detect_sub(k, v.get("title", "")) == "其它检测方法"]
        ratio = len(others) / max(1, sum(
            1 for v in (g.get("details") or {}).values()
            if v.get("category") == "test"))
        print("  {} 兜底率 {:.1%}（{} 条检测标准中 {} 条未归类）".format(
            "✓" if ratio < 0.05 else "✗", ratio,
            sum(1 for v in (g.get("details") or {}).values()
                if v.get("category") == "test"), len(others)))
        if ratio >= 0.05:
            bad += 1
        for k in others[:10]:
            print("      未归类:", k, (g["details"][k].get("title") or "")[10:46])
    else:
        print("  （库不存在，跳过）")

    print()
    if bad == 0:
        print("细分规则全部通过（{} 条用例）".format(len(CASES) + len(PRODUCT_CASES)))
        return 0
    print("{} 条不符合预期".format(bad))
    return 1


if __name__ == "__main__":
    sys.exit(main())
