def sub_category(std_no: str, title: str, cat: str) -> str:
    """按一级分类分派到二级细分。"""
    if cat == "test":
        return detect_sub(std_no, title)
    if cat == "product":
        return product_sub(std_no, title)
    if cat == "sys":
        return sys_sub(std_no, title)
    if cat == "prod":
        return prod_sub(std_no, title)
    return assoc_sub(std_no, title)
