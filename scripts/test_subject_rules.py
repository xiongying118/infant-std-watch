def main():
    bad = 0
    for title, want, note in CASES:
        got = V.subject_of(title)
        ok = (got == want)
        if not ok:
            bad += 1
        short = title.replace("食品安全国家标准 ", "")[:34]
        print("  {} {:<36s} → {:<16s} {}".format(
            "✓" if ok else "✗", short, str(got),
            ("(期望 " + str(want) + ") ") if not ok else note))

    # ---- 替代关系判定（含 cands[0] 未实施的坑） ----
    # 注意：这里用别名 VV，不要 `import verify_validity2 as V` ——
    # 函数内 import 会把 V 变成局部变量，上面那些用 V 的语句就 UnboundLocalError。
    print()
    print("=== 替代关系判定 ===")
    import io
    import json
    import verify_validity2 as VV
    gp = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                      "..", "data", "general_refs.json")
    allstd = []
    if os.path.exists(gp):
        g = json.load(io.open(gp, encoding="utf-8"))
        allstd = [{"std_no": k, "title": v.get("title", ""),
                   "implement_date": v.get("implement_date", ""),
                   "publish_date": v.get("publish_date", "")}
                  for k, v in (g.get("details") or {}).items()]
    if allstd:
        for no, ti, imp, want_v, want_newer in SUBJECT_CASES:
            r = VV.validity_state(no, ti, imp, allstd)
            ok = (r["validity"] == want_v and (r.get("newer") or None) == want_newer)
            if not ok:
                bad += 1
            print("  {} {} → {} / {}{}".format(
                "✓" if ok else "✗ 错", no, r["validity"], r.get("newer"),
                "" if ok else "  (期望 {} / {})".format(want_v, want_newer)))
    else:
        print("  （库不存在，跳过）")
    print()
    if bad:
        print("{} 条不符合预期".format(bad))
        return 1
    print("全部通过（归一化 {} 条 + 替代关系 {} 条）".format(
        len(CASES), len(SUBJECT_CASES)))
    return 0


