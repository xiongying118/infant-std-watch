def subject_of(title: str) -> str | None:
    """从标准名里提取检测对象。提不出返回 None。

    规则里 name 为 None 的是"**排除项**"：命中就说明这条标准不是我们要找的东西
    （如"乳铁蛋白"不是"铁"），直接返回 None，不再往下匹配。
    """
    if not title or not _METHOD_HINT.search(title):
        return None
    for rx, name in _SUBJECT_RES:
        if rx.search(title):
            return name          # 可能是 None（排除项）
    return None


