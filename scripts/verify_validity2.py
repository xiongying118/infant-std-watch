#   它代替的是 GB/T 22507-2008「动植物油脂 植物油中反式脂肪酸异构体含量的测定」
#   ——**是油脂方法，不是乳粉方法**。婴配乳粉基质是乳蛋白、脂肪含量低，
#   直接拿它测婴配是方法选错。
#   源站标题只写"食品中"，看不出这个限制，光看标题会误判。
#   所以：**适用范围与"主基质不符"的标准，不构成同检测对象的替代关系。**
SCOPE_LIMIT = {
    # 标准号主干 → 适用基质描述
    "GB5009.257": "动植物油脂及含油脂食品（不适合乳粉等低脂基质）",
    "GB5009.254": "动植物油脂",
    "GB5009.236": "动植物油脂",
    "GB5009.37": "油脂",
}


def _scope_conflict(std_no_a: str, std_no_b: str) -> str | None:
    """两个标准适用范围冲突时返回说明；不冲突返回 None。

    判定口径：一方限定了基质（SCOPE_LIMIT 里有登记），另一方是该基质的
    天然对应品类（乳/乳粉/婴幼儿），就认为不构成替代。

    ★ 撤回过一个错误的反向规则（2026-10-03，教训记在这）★
      曾加过"婴配专用方法（GB 5413.x）不被通用方法（GB 5009.x）替代"，
      理由是"5413.22 是婴配专用、5009.87 是通用，后者未声明替代前者"。
      **这个推理是错的**，官方数据直接否掉了它：
        GB 5009.87-2016 详情页「代替与引用」明确写着
          代替了：GB5413.22—2010《婴幼儿食品和乳品中磷的测定》
        GB 5009.158-2016 详情页同样写着
          代替了：GB5413.10—2010《婴幼儿食品和乳品中维生素K1 的测定》
      官方既然声明了替代，就是替代。**不能凭"看起来范围不同"推翻官方声明。**
      → 正确做法是走 REPLACES_BY（官方代替关系表），不是在这里猜。

    ★ 教训：不要用"推理"替代"查证" ★
      这个错误让 GB 5413.22 被误判成"现行有效"、
      同时把真正该判失效的 GB 5413.10 挡在替代链外 —— 一个规则同时错两次。
      涉及"某标准是否失效"这类结论，一律以官方详情页的代替关系为准。
    """
    a, b = std_base(std_no_a), std_base(std_no_b)
    if a == b:
        return None                      # 同标准号，不受此限
    limit = SCOPE_LIMIT.get(a) or SCOPE_LIMIT.get(b)
    if not limit:
        return None
    other = b if SCOPE_LIMIT.get(a) else a
    # 另一方是乳/乳粉类标准 → 基质不符，不是替代
    if re.search(r"5413|乳|婴幼儿", other):
        limited = a if SCOPE_LIMIT.get(a) else b
        return "{} 限定适用范围（{}），与乳基质标准不构成替代关系".format(
            limited, limit)
    return None


# ============================================================
# ★ 官方代替关系表（权威，优先于任何推断） ★
# ============================================================
# 数据来源：CFSA 官方详情页 staticPages/<ID>.html 的「代替与引用」章节，
# 2026-10-03 逐条抓取核实。格式：新版标准号 → 它明确代替的旧版标准号。
#
# ★ 为什么必须有这张表 ★
#   官方详情页把"代替了哪些标准"写得清清楚楚（人可读），
#   但检索接口不返回这个字段 —— 只能靠标题 + 检测对象去猜，
#   而猜错的后果是**把已失效标准当成现行**（实验室照着错版本做检测）。
#   猜错的真实案例（2026-10-03）：
#     我曾判定"GB 5413.22 婴配专用，GB 5009.87 通用，所以不构成替代"，
#     保留了 5413.22；实际官方明确写了 5009.87 代替 5413.22。
#   所以：**凡是官方声明了代替关系的，一律采信；表里没有的才走推断，
#   且推断结果只用于"提示"，不用于"判定失效"。**
REPLACES_BY: dict[str, list[str]] = {
    "GB5009.87-2016": ["GB5413.22-2010", "GB/T5009.87-2003"],
    "GB5009.158-2016": ["GB5413.10-2010", "GB/T5009.158-2003"],
}


def official_replacement(std_no: str) -> str:
    """查官方声明的替代者。返回**新版**标准号，没查到返回空串。

    ★ 只查"我被谁代替"这一个方向 ★
      踩过：一开始查双向（既查"我代替谁"、也查"谁代替我"），
      结果 GB 5009.158-2016 自己被算成"被 GB 5413.10-2010 代替"——
      方向反了。新版当然没有被旧版代替。
      用途是判定"我是否已失效"，只需要"谁代替了我"这一个方向。
    """
    my = re.sub(r"\s+", "", std_no or "").upper().replace("—", "-")
    for new, olds in REPLACES_BY.items():
        n_key = re.sub(r"\s+", "", new).upper().replace("—", "-")
        for o in olds:
            o_key = re.sub(r"\s+", "", o).upper().replace("—", "-")
            if my != o_key:
                continue
            # 同一主干互为新旧版时，只在"我年份更老"时才判被替代
            if std_base(new) == std_base(std_no) and n_key >= my:
                return ""                # 同主干且我是新版
            # 归一成「GB 5009.158-2016」的带空格写法，与 all_std 里的标准号一致
            return re.sub(r"^(GB/?T?)(\d)", r"\1 \2", n_key)
    return ""


def _equivalent_method(t1: str, t2: str) -> bool:
    """两版是不是等价的检测方法（可互相替代）。

    只要一边是"快速/筛查"而另一边不是，就不构成替代关系。
    """
    return bool(_SCREENING_RE.search(t1 or "")) == bool(_SCREENING_RE.search(t2 or ""))


def validity_state(std_no: str, title: str, implement_date: str,
                   all_std: list[dict], today=None) -> dict:
    """判定单条标准的有效性。

    all_std: 全部标准（至少含 std_no / title / implement_date）
    两层判定：
      1. 同标准号内有更新的已实施版本 → 被替代
      2. **不同标准号但检测对象相同**，且有更新的已实施版本 → 被替代 ★关键★
    """
    t = today or date.today()
    my_base = std_base(std_no)
    my_imp = parse_date(implement_date)
    my_subj = subject_of(title)

    # ================================================================
    # 第 0 层：官方声明的代替关系 —— **最高优先级，直接采信**
    # ================================================================
    # ★ 为什么放在最前面 ★
    #   官方详情页「代替与引用」章节写明的关系是权威事实。
    #   后面 1/2 层是"靠标题 + 检测对象推断"，推断可能对、也可能错；
    #   官方数据与推断冲突时，一律以官方为准。
    #   真实案例（2026-10-03）：
    #     我曾用"婴配专用 vs 通用方法范围不同"推断 5413.22 不被 5009.87 替代，
    #     官方详情页却明确写着 GB 5009.87-2016 代替了 GB5413.22-2010。
    #     凭推断推翻官方声明 → 把已失效标准当成现行，实验室会照错版本做检测。
    _off = official_replacement(std_no)
    if _off:
        _v = next((x for x in all_std
                   if re.sub(r"\s+", "", x.get("std_no", "")).upper()
                   == re.sub(r"\s+", "", _off).upper()), None)
        _imp_new = parse_date(_v.get("implement_date")) if _v else None
        # 官方已声明替代，但新版还没实施 → 现在仍执行这一版（提前准备换版）
        if _imp_new is None or _imp_new <= t:
            st, desc = _impl_state(implement_date, t)
            return {"validity": "已被替代",
                    "reason": "官方详情页「代替与引用」列明由 {} 代替".format(_off),
                    "newer": _off,
                    "newer_title": (_v or {}).get("title", ""),
                    "cross_no": True,
                    "implement_state": st,
                    "implement_desc": desc}

    # 候选替代者：同号 或 同检测对象
    def newer_candidates():
        out = []
        for v in all_std:
            v_no = v.get("std_no", "")
            v_base = std_base(v_no)
            v_imp = parse_date(v.get("implement_date"))
            if v_imp is None or my_imp is None:
                continue
            if v_imp <= my_imp:
                continue                     # 不比我新
            same_no = (v_base == my_base)
            if not same_no:
                # ★ 适用基质不符 → 不构成替代 ★
                #   GB 5009.257 是动植物油脂方法，不是乳粉方法；
                #   它替代的是 GB/T 22507（油脂），不是 GB 5413.36（婴配乳品）。
                #   源站标题只写"食品中"，看不出这个限制 —— 必须靠 SCOPE_LIMIT 登记。
                if _scope_conflict(std_no, v_no):
                    continue
                # ★ 跨标准号替代的前提：两版是"等价的检测方法" ★
                #   踩过：GB/T 22388（原料乳与乳制品中三聚氰胺**检测方法**）
                #      被判成"被 GB/T 22400（**快速检测**）替代"而被过滤掉。
                #   但快速检测只用于筛查，出报告必须用全方法 —— 二者是互补，
                #   不是替代。缺了这道判断，实验室会拿筛查法当仲裁法出报告。
                if not _equivalent_method(title, v.get("title", "")):
                    continue
            same_subj = (my_subj is not None
                         and subject_of(v.get("title", "")) == my_subj)
            if same_no or same_subj:
                out.append((v, "同标准号" if same_no else "同一检测对象"))
        # 实施日期新的优先
        out.sort(key=lambda x: x[0].get("implement_date") or "", reverse=True)
        return out

    cands = newer_candidates()

    if cands:
        # ★ 必须在候选里挑"已实施"的那条，不能直接取 cands[0] ★
        #   踩过（用户指出"GB 5413.27 是失效的"）：
        #     脂肪酸检测对象下的版本按实施日期倒序是
        #       GB 5009.168-2026（2027-08-18，未实施）
        #       GB 5009.168-2016（2017-06-23，已实施）★ 这条才是替代者
        #       GB 5413.27-2010  （2010-06-01，被我判定的对象）
        #     直接取 cands[0] 拿到 2027 版，它还没实施 →
        #     走不进"已被替代"分支 → GB 5413.27 被错判成"现行有效"。
        #   这是**漏判已发生**的替代关系，实验室会以为老方法还能用。
        #
        #   正确口径：**只要存在更新的已实施版本，我这条就是被替代了**。
        #   未来还有新版（未实施）不影响现在的判定，那属于"提前知道"。
        effective = [c for c in cands if parse_date(c[0].get("implement_date")) <= t]
        if effective:
            v0, why = effective[0]
            return {"validity": "已被替代",
                    "reason": "已被 {} 替代（{} 实施，{}）".format(
                        v0.get("std_no"), v0.get("implement_date"), why),
                    "newer": v0.get("std_no"),
                    "newer_title": v0.get("title", ""),
                    "cross_no": why == "同一检测对象",
                    "implement_state": _impl_state(implement_date, t)[0],
                    "implement_desc": _impl_state(implement_date, t)[1]}

    st, desc = _impl_state(implement_date, t)
    return {"validity": "现行有效",
            "reason": "同号与同检测对象下均无更新的已实施版本",
            "newer": None, "newer_title": "", "cross_no": False,
            "implement_state": st, "implement_desc": desc}


def _impl_state(imp, today) -> tuple[str, str]:
    d = parse_date(imp)
    if d is None:
        return "日期待定", "官方未给实施日期"
    delta = (d - today).days
    if delta < 0:
        return "已实施", "已于 {} 实施（{} 天前）".format(imp, abs(delta))
    if delta == 0:
        return "即将实施", "今日实施（{}）".format(imp)
    return "即将实施", "还有 {} 天实施（{}）".format(delta, imp)


def audit(all_std: list[dict], today=None) -> list[dict]:
    """全量核对。all_std 每条需含 std_no / title / implement_date。"""
    t = today or date.today()
    out = []
    for v in all_std:
        r = validity_state(v.get("std_no", ""), v.get("title", ""),
                           v.get("implement_date", ""), all_std, t)
        out.append({
            "std_no": v.get("std_no"), "title": v.get("title"),
            "publish_date": v.get("publish_date"),
            "implement_date": v.get("implement_date"),
            "subject": subject_of(v.get("title", "")),
            **r,
        })
    return out


